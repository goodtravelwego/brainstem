// Convert the reference's public SVG icon primitives to native Android vectors.
const fs = require('node:fs');
const vm = require('node:vm');
const src = fs.readFileSync('reference/pbm.html', 'utf8');
const base = src.slice(src.indexOf('const IC='), src.indexOf('const icon='));
const extraStart = src.indexOf('Object.assign(IC,');
const extra = src.slice(extraStart, src.indexOf('});', extraStart) + 3);
const sandbox = Object.create(null);
vm.runInNewContext(base + extra + ';result=JSON.stringify(IC)', sandbox,
  {timeout:1000,contextCodeGeneration:{strings:false,wasm:false}});
const icons = JSON.parse(sandbox.result);
const entries = [];
for (const [name, svg] of Object.entries(icons)) {
  const paths = [];
  for (const match of svg.matchAll(/<(path|circle|rect|line)\b([^>]*?)\/?\s*>/g)) {
    const attrs = Object.fromEntries([...match[2].matchAll(/([\w-]+)="([^"]*)"/g)].map(m=>[m[1],m[2]]));
    const number = (key, fallback=0) => Number(attrs[key] ?? fallback);
    let path;
    if (match[1] === 'path') path = attrs.d;
    if (match[1] === 'circle') {
      const x=number('cx'),y=number('cy'),r=number('r');
      path=`M${x-r},${y}a${r},${r} 0,1 0,${2*r},0a${r},${r} 0,1 0,${-2*r},0`;
    }
    if (match[1] === 'line') path=`M${number('x1')},${number('y1')}L${number('x2')},${number('y2')}`;
    if (match[1] === 'rect') {
      const x=number('x'),y=number('y'),w=number('width'),h=number('height'),r=number('rx');
      path=`M${x+r},${y}H${x+w-r}Q${x+w},${y} ${x+w},${y+r}V${y+h-r}Q${x+w},${y+h} ${x+w-r},${y+h}H${x+r}Q${x},${y+h} ${x},${y+h-r}V${y+r}Q${x},${y} ${x+r},${y}Z`;
    }
    if (!path) throw Error(`Unsupported icon: ${name}`);
    paths.push(`    <path android:pathData="${path}" android:fillColor="${attrs.fill === 'currentColor' ? '#FF000000' : '@android:color/transparent'}" android:strokeColor="#FF000000" android:strokeWidth="1.8" android:strokeLineCap="round" android:strokeLineJoin="round" />`);
  }
  if (!paths.length) throw Error(`Empty icon: ${name}`);
  const resource=`ref_icon_${name.toLowerCase()}`;
  fs.writeFileSync(`app/src/main/res/drawable/${resource}.xml`,
    `<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n${paths.join('\n')}\n</vector>\n`);
  entries.push(`    "${name}" to R.drawable.${resource},`);
}
fs.writeFileSync('app/src/main/java/com/brainstem/stimulate/ReferenceIcons.kt',
  `package com.brainstem.stimulate\n\n// Generated by tools/extract-icons.cjs from the public reference SVG paths.\nval REFERENCE_ICONS = mapOf(\n${entries.join('\n')}\n)\n`);
console.log(`Converted ${entries.length} reference icons to native vectors.`);
